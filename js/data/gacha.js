//   requires : 出る条件（隠し。画面には何も表示しません）
//            { 出るモンスターID: [図鑑に登録しておく必要があるモンスターID, ...] }
//            全部登録済みになるまで、そのモンスターは抽選から外れます（ラインナップの一覧にはふつうに載ります）
// ============================================================
